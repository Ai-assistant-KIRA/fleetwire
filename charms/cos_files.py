"""Copy the Prometheus alert rules and the Grafana dashboard into the charms.

deploy/prometheus/rules and deploy/grafana/dashboards are the sources. The
charms carry copies, because COS Lite reads rules and dashboards from the
charms related to it. Each charm's unit tests compare its copies with what
this script writes, so a copy that drifts from its source fails the tests:

    charms/cos_files.py          write the copies
    charms/cos_files.py --check  exit 1 if a copy is out of date

The dashboard goes into the API charm only, unchanged: Grafana would list
one copy for every charm that ships it.

The rules are split by the service whose metrics they read. The Prometheus
charm restricts each expression in a charm's rules to that charm's
application (it adds juju_model, juju_model_uuid and juju_application
matchers), so a rule on ingest metrics shipped by the API charm would never
match, and the absent() terms for the other services would fire forever.
Each charm gets the rules on its own metrics and the liveness rules, and
FleetwireServiceDown keeps only the absent() term of the charm's own job.
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

import yaml

CHARMS = pathlib.Path(__file__).resolve().parent
REPO = CHARMS.parent
RULES = REPO / "deploy/prometheus/rules/fleetwire.yml"
DASHBOARD = REPO / "deploy/grafana/dashboards/fleetwire.json"

# The charm of each service that serves metrics. The charms name their
# scrape jobs fleetwire-<service>, as deploy/prometheus/prometheus.yml does.
CHARM = {"api": "fleetwire-api-k8s", "ingest": "fleetwire-ingest-k8s", "bridge": "fleetwire-bridge-k8s"}
RULES_COPY = "src/prometheus_alert_rules/fleetwire.yml"
DASHBOARD_COPY = "src/grafana_dashboards/fleetwire.json"
DASHBOARD_CHARM = "fleetwire-api-k8s"

# The service that exports a metric, by name prefix.
EXPORTER = {
    "fleetwire_api_": "api",
    "fleetwire_crl_": "api",
    "fleetwire_ingest_": "ingest",
    "fleetwire_bridge_": "bridge",
}
METRIC = re.compile(r"\bfleetwire_[a-z0-9_]+")
RECORDED = re.compile(r"\bfleetwire:[a-z0-9_:]+")
# A rule on the up series of the fleetwire jobs, which every charm has.
LIVENESS = re.compile(r'\bup\{job=~?"fleetwire-')
ABSENT_TERM = re.compile(r'\s+or\s+absent\(up\{job="fleetwire-(?P<service>[a-z]+)"\}\)')


def rule_name(rule: dict) -> str:
    return rule.get("alert") or rule.get("record") or "?"


def services_of(rule: dict, recorded: dict[str, str]) -> set[str]:
    """The services whose charm ships this rule."""
    expr = rule["expr"]
    found: set[str] = set()
    for metric in METRIC.findall(expr):
        service = next((s for prefix, s in EXPORTER.items() if metric.startswith(prefix)), None)
        if service is None:
            raise ValueError(f"{rule_name(rule)}: no charm is known to serve {metric}; add it to EXPORTER")
        found.add(service)
    for name in RECORDED.findall(expr):
        if name not in recorded:
            raise ValueError(f"{rule_name(rule)}: {name} is not recorded by an earlier rule")
        found.add(recorded[name])
    if not found and LIVENESS.search(expr):
        return set(CHARM)
    if len(found) != 1:
        raise ValueError(f"{rule_name(rule)}: reads the metrics of {sorted(found) or 'no service'}; split it by hand")
    return found


def split_rules(source: dict) -> dict[str, dict]:
    """The rules file of each service's charm."""
    recorded: dict[str, str] = {}
    out: dict[str, dict] = {service: {"groups": []} for service in CHARM}
    for group in source["groups"]:
        rules: dict[str, list[dict]] = {service: [] for service in CHARM}
        for rule in group["rules"]:
            services = services_of(rule, recorded)
            if "record" in rule:
                (recorded[rule["record"]],) = services
            for service in services:
                own = dict(rule)
                own["expr"] = ABSENT_TERM.sub(
                    lambda m, s=service: m.group(0) if m.group("service") == s else "", rule["expr"]
                )
                rules[service].append(own)
        for service, kept in rules.items():
            if kept:
                out[service]["groups"].append({**group, "rules": kept})
    return out


class _Dumper(yaml.SafeDumper):
    """Writes multi-line strings (the longer expressions) as literal blocks."""


def _str(dumper: yaml.SafeDumper, value: str) -> yaml.Node:
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


_Dumper.add_representer(str, _str)


def render_rules(service: str, rules: dict) -> str:
    header = (
        f"# Generated by charms/cos_files.py from deploy/prometheus/rules/fleetwire.yml:\n"
        f"# the rules on fleetwire-{service}'s metrics and the liveness rules.\n"
        f"# Edit the source and run the script; do not edit this copy.\n"
    )
    return header + yaml.dump(rules, Dumper=_Dumper, sort_keys=False, width=1000, allow_unicode=True)


def expected() -> dict[pathlib.Path, str]:
    """The content of every copy, by path."""
    split = split_rules(yaml.safe_load(RULES.read_text()))
    files = {CHARMS / CHARM[s] / RULES_COPY: render_rules(s, rules) for s, rules in split.items()}
    files[CHARMS / DASHBOARD_CHARM / DASHBOARD_COPY] = DASHBOARD.read_text()
    return files


def same(path: pathlib.Path, content: str) -> bool:
    if not path.is_file():
        return False
    if path.suffix == ".yml":
        # Compared as data, so a different PyYAML emitter is no drift.
        return yaml.safe_load(path.read_text()) == yaml.safe_load(content)
    return path.read_text() == content


def drifted(charm: str | None = None) -> list[pathlib.Path]:
    """The copies that differ from what the script writes (for one charm, if given)."""
    return [
        path
        for path, content in expected().items()
        if (charm is None or path.parts[len(CHARMS.parts)] == charm) and not same(path, content)
    ]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only report copies that are out of date")
    args = parser.parse_args()
    if args.check:
        stale = drifted()
        for path in stale:
            print(f"out of date: {path.relative_to(REPO)} (run charms/cos_files.py)", file=sys.stderr)
        return 1 if stale else 0
    for path, content in expected().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f"wrote {path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
